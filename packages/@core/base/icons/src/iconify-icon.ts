function resolveLocalIcon(icon: string) {
  const alias = localIconAliases[icon];
  if (alias) {
    return alias;
  }
  if (!icon.startsWith('lucide:')) {
    return undefined;
  }
  return localLucideIcons[icon.slice('lucide:'.length)];
}

function listLocalIcons(prefix = '') {
  const names = new Set([
    ...Object.keys(localIconAliases),
    ...Object.keys(localLucideIcons).map((name) => `lucide:${name}`),
  ]);
  const prefixToken = prefix ? `${prefix}:` : '';
  return [...names]
    .filter((name) => !prefixToken || name.startsWith(prefixToken))
    .toSorted();
}

const IconifyIcon = defineComponent({
  name: 'IconifyIcon',
  inheritAttrs: false,
  props: {
    icon: {
      required: true,
      type: String,
    },
  },
  setup(props, { attrs }) {
    return () => {
      const localIcon = resolveLocalIcon(props.icon);
      if (localIcon) {
        return h(localIcon, attrs);
      }
      // Registered SVG/brand/framework icons are rendered offline. Checking
      // the registry instead of trusting a prefix prevents invalid resources
      // from being fetched at runtime.
      if (hasOfflineIcon(props.icon)) {
        return h(OfflineIcon, { ...attrs, icon: props.icon });
      }
      // A large share of icon names arrives from runtime data (database menu
      // icons, donation methods, role meta) where only the syntax is validated.
      // Map those to an equivalent registered icon before giving up, so a
      // different icon-set prefix or a near-synonym keeps a meaningful glyph.
      const inferred = resolveFallbackName(
        props.icon,
        (candidate) =>
          Boolean(resolveLocalIcon(candidate)) || hasOfflineIcon(candidate),
      );
      if (inferred) {
        const inferredLocal = resolveLocalIcon(inferred);
        return inferredLocal
          ? h(inferredLocal, { ...attrs, 'data-inferred-icon': props.icon })
          : h(OfflineIcon, {
              ...attrs,
              'data-inferred-icon': props.icon,
              icon: inferred,
            });
      }
      // Runtime icon-network loading is intentionally disabled. Unknown icons
      // render nothing at all — the old brand fallback mark is deprecated.
      return null;
    };
  },
});

export { IconifyIcon, listLocalIcons, resolveLocalIcon };
